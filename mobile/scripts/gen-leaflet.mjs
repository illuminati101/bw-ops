// Inlines Leaflet into the app so maps work without a CDN (tiles still come from the network).
import { readFileSync, writeFileSync } from 'node:fs';
const js = readFileSync(new URL('../node_modules/leaflet/dist/leaflet.js', import.meta.url), 'utf8');
const css = readFileSync(new URL('../node_modules/leaflet/dist/leaflet.css', import.meta.url), 'utf8');
writeFileSync(new URL('../src/map/leafletAssets.ts', import.meta.url),
  `// Generated by scripts/gen-leaflet.mjs from leaflet@1.9.4 (BSD-2-Clause). Do not edit.\nexport const LEAFLET_JS = ${JSON.stringify(js)};\nexport const LEAFLET_CSS = ${JSON.stringify(css)};\n`);
console.log('leafletAssets.ts written');
